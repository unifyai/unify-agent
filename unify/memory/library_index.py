"""links.json and INDEX.md for a memory library.

Both are generated by the harness for every copy of the library, from the tree and the item statuses (the item
records; ``on-trial`` without them). A model never writes them. The same inputs give the same bytes:
everything is sorted, and nothing depends on time, paths or the order files were written in. ``links.json``
holds every item, hidden ones included. ``INDEX.md`` leaves out ``retired`` items, which stay reachable through
``memory.show``. The status names and evidence levels are :mod:`.item_states`'s.

:data:`INDEX_VIEW_TOKENS` is the size past which the gate's G4 notes the index's growth (a note, never a refusal);
``memory.index("<section>")`` prints any section in full.
"""

from __future__ import annotations

import json
from collections.abc import Callable

from .item_states import HIDDEN, ON_TRIAL, STATUSES
from .layout import FUNCTION_ID, NOTE_ID, Library
from .library_helper import item_count, split_index

INDEX_VIEW_TOKENS = 4000
# STATUSES and HIDDEN (imported above from item_states) stay importable from here: other modules read them here
#: a function's effect as the gate derives it from its recorded covers, for the writer's records only (never served)
EFFECTS = ("read", "write", "unknown")
StatusOf = Callable[[str], str]
#: an item's support (:func:`.item_records.support`: ``{"episodes", "confirmed_uses"}``), None for none recorded
SupportOf = Callable[[str], "dict | None"]
#: an item's example call as the index shows it (:func:`.example_view.example_of`), None for none
ExampleOf = Callable[[str], "str | None"]
#: an item's applicability signature (``input``, ``output``, ``relations``, ``constraints``), None for none
SignatureOf = Callable[[str], "dict | None"]
#: What the head says of the ``input:`` line (both heads carry it).
INPUT_LINE_HEAD = (
    "A procedure's line may be followed by an `input:` line: the structure of the input it was saved against "
    "(key paths with value types) and the relations its result had to that "
    "input.\n"
)
#: Key paths an ``input:`` line shows before it says how many more there are.
INPUT_LINE_PATHS = 12
INDEX_HEAD = (
    "# Memory index\n\n"
    "Generated by the harness from the library; never edit it. One line per item: a function as "
    "`memory.<package>.<module>:<name>(<parameters>)`, a note as `notes/<topic>/<slug>.md`, each with its "
    "status in brackets and the items it links to either way. Every line's brackets also say what the item rests on: `curated item from <n> "
    "episodes`, with its confirmed uses (uses whose outcome confirmed it) when it has any. A function's line may "
    "be followed by "
    "an `e.g.` line: a call of it quoted from one "
    "of its tests, on values that test loads from recorded fixtures, with the test it comes from. "
    '`memory.show("<item>")` shows one in full.\n' + INPUT_LINE_HEAD
)
_EMPTY = "\nThe library is empty.\n"


def on_trial(item: str) -> str:
    return ON_TRIAL


def _status(status_of: StatusOf | None, item: str) -> str:
    s = (status_of or on_trial)(item)
    if s not in STATUSES:
        raise ValueError(f"unknown status {s!r} for {item}")
    return s


def signature_text(signature: "dict | None") -> str:
    """The ``input:`` line's text for an applicability signature: its input's key paths with their value types (a
    file's format first), at most :data:`INPUT_LINE_PATHS` of them, then the relations it was saved with, every key
    as written. ``""`` when it has no readable input shape."""
    from .memory_helper import signature as key_paths

    if not isinstance(signature, dict) or not isinstance(signature.get("input"), dict):
        return ""
    desc = signature["input"]
    try:
        paths = key_paths(desc)
    except Exception:  # noqa: BLE001 - an unreadable shape shows no line
        return ""
    if not paths:
        return ""
    shape = desc.get("shape") if isinstance(desc.get("shape"), dict) else {}
    fmt = shape.get("format") if desc.get("kind") == "file" else None
    shown = [f"{p}: {t}" for p, t in sorted(paths.items())]
    text = (f"{fmt} " if isinstance(fmt, str) and fmt else "") + "{" + ", ".join(shown[:INPUT_LINE_PATHS])
    if len(shown) > INPUT_LINE_PATHS:
        text += f", and {len(shown) - INPUT_LINE_PATHS} more"
    text += "}"
    rel = signature.get("relations")
    if isinstance(rel, list) and rel:
        text += "; relations: " + ", ".join(str(r) for r in rel)
    return text


def _support(support_of: SupportOf | None, item: str) -> str:
    """``, curated item from <n> episodes[, <m> confirmed uses]`` for *item* (nothing without *support_of*)."""
    facts = support_of(item) if support_of is not None else None
    if facts is None:
        return ""
    from .item_records import support_text

    return ", " + support_text("curated item", facts)


def build_links(lib: Library) -> dict:
    """Every item's links both ways, and each written link that names no item of the right kind.

    A function links to the notes its ``Notes:`` line names. A note links to the functions its ``uses:`` list
    names. ``linked_from`` is derived from those. A dangling link names its source, its target and why:
    ``missing`` (well formed, no such item), ``malformed`` (not an id of the kind it must name) or ``not a
    <kind>``.
    """
    items: dict[str, dict] = {}
    for f in lib.functions:
        items[f.item_id] = {
            "kind": "function",
            "path": f.path,
            "links_to": sorted(set(f.notes)),
            "linked_from": [],
        }
    for n in lib.notes:
        items[n.item_id] = {
            "kind": "note",
            "path": n.item_id,
            "links_to": sorted(set(n.uses)),
            "linked_from": [],
        }
    dangling: list[dict] = []
    for src in sorted(items):
        want = "note" if items[src]["kind"] == "function" else "function"
        pattern = NOTE_ID if want == "note" else FUNCTION_ID
        for dst in items[src]["links_to"]:
            target = items.get(dst)
            if target is None:
                why = "missing" if pattern.match(dst) else "malformed"
                dangling.append({"from": src, "to": dst, "why": why})
            elif target["kind"] != want:
                dangling.append({"from": src, "to": dst, "why": f"not a {want}"})
            else:
                target["linked_from"].append(src)
    for row in items.values():
        row["linked_from"].sort()
    return {"version": 1, "items": items, "dangling": dangling}


def render_links(links: dict) -> str:
    """``links.json``: sorted keys, one trailing newline."""
    return json.dumps(links, sort_keys=True, indent=1, ensure_ascii=False) + "\n"


def _linked(links: dict, item: str, kind: str, shown: set[str]) -> list[str]:
    row = links["items"][item]
    both = set(row["links_to"]) | set(row["linked_from"])
    return sorted(i for i in both if i in shown and links["items"][i]["kind"] == kind)


def render_index(
    lib: Library,
    links: dict,
    status_of: StatusOf | None = None,
    example_of: ExampleOf | None = None,
    signature_of: "SignatureOf | None" = None,
    support_of: SupportOf | None = None,
) -> str:
    """``INDEX.md``: one section per package that lists a function (heading: its docstring's first sentence)
    and one per notes topic that lists a note. Each function line gives its id with its signature, its summary,
    its status and its notes (no effect and no test breadth: nothing a test or a judgement of its code gave is
    shown); when *example_of* gives the function's example call (its record's, re-quoted from the tree), a
    second line ``  e.g. `<call>` (<test id>)`` follows; every item's support (*support_of*, from the item records: its
    kind, the episodes it comes from and its confirmed uses; None shows nothing) follows its status; when
    *signature_of* gives a function's applicability signature, a line ``  input: <shape>`` follows (:func:`signature_text`). Each note
    line gives its path, its description, its status and its functions.
    """
    status = {i: _status(status_of, i) for i in links["items"]}
    shown = {i for i, s in status.items() if s not in HIDDEN}
    by_pkg: dict[str, list[str]] = {}
    for f in sorted(lib.functions, key=lambda f: f.item_id):
        if f.item_id not in shown:
            continue
        line = (
            f"- `{f.module}:{f.signature}`"
            + (f" — {f.summary}" if f.summary else "")
            + f" [{status[f.item_id]}{_support(support_of, f.item_id)}]"
        )
        notes = _linked(links, f.item_id, "note", shown)
        if notes:
            line += "; notes: " + ", ".join(notes)
        example = example_of(f.item_id) if example_of is not None else None
        if example:
            line += f"\n  e.g. {example}"
        sig = signature_text(signature_of(f.item_id)) if signature_of is not None else ""
        if sig:
            line += f"\n  input: {sig}"
        by_pkg.setdefault(f.module.split(".")[1], []).append(line)
    by_topic: dict[str, list[str]] = {}
    for n in sorted(lib.notes, key=lambda n: n.item_id):
        if n.item_id not in shown:
            continue
        about = (
            n.description if not n.error else f"(front matter unreadable: {n.error})"
        )
        line = f"- `{n.item_id}` — {about} [{status[n.item_id]}{_support(support_of, n.item_id)}]"
        fns = _linked(links, n.item_id, "function", shown)
        if fns:
            line += "; functions: " + ", ".join(fns)
        by_topic.setdefault(n.item_id.split("/")[1], []).append(line)
    out = [INDEX_HEAD]
    for pkg in sorted(by_pkg):
        summary = lib.packages.get(pkg, "")
        out.append(
            f"\n## memory.{pkg}"
            + (f" — {summary}" if summary else "")
            + "\n\n"
            + "\n".join(by_pkg[pkg])
            + "\n",
        )
    for topic in sorted(by_topic):
        out.append(f"\n## notes/{topic}\n\n" + "\n".join(by_topic[topic]) + "\n")
    if not by_pkg and not by_topic:
        out.append(_EMPTY)
    return "".join(out)


def listed(index: str) -> int:
    """How many items an index lists."""
    return sum(item_count(body) for _, body in split_index(index)[1])


